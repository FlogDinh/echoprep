#!/usr/bin/env python3
"""Find where each Listening question is answered in its audio, for "play from this question" in review.

Input: word timestamps from speech recognition (one JSON per audio, named v8-t1-s2.json, v9-t3-s4.json:
[[word,start,end],...]; made with mlx-whisper small.en from the same audio the site plays or the learner picks).
The transcript is aligned to the recognised words; each question's anchor is its evidence cue
(Qn label, vol8/vol9-evidence-cues.json) or its gap answer inside the evidence paragraph, else the paragraph start.
Output: dist/audio-times.js  window.AUDIO_TIMES={'listening:8:1':{'1':[section,seconds],...}}
Usage: python3 scripts/align-audio-times.py <asr-dir>
"""
import json,re,sys,pathlib,difflib
ROOT=pathlib.Path(__file__).resolve().parents[1]
LEAD=5.0  # start a little before the answer so the question is heard in context
tok=lambda t:[w for w in (re.sub(r'[^a-z0-9]','',x) for x in t.lower().replace('-',' ').split()) if w]

def load(path):
 s=path.read_text();return json.loads(s[s.index('=')+1:].rstrip().rstrip(';'))

def section_of(test,n):
 for i,(a,b) in enumerate(test.get('groups') or [[1,10],[11,20],[21,30],[31,40]]):
  if a<=n<=b:return i+1

def align(segs,words):
 T=[];owner=[];marks={}
 for k,seg in enumerate(segs):
  for w in tok(seg['text']):
   if re.fullmatch(r'q\d{1,2}',w):marks[int(w[1:])]=len(T);continue
   T.append(w);owner.append(k)
 A=[re.sub(r'[^a-z0-9]','',w[0].lower()) for w in words]
 times=[None]*len(T);matched=0
 for a,b,size in difflib.SequenceMatcher(None,T,A,autojunk=False).get_matching_blocks():
  for i in range(size):times[a+i]=words[b+i][1];matched+=1
 known=[i for i,t in enumerate(times) if t is not None]
 for i in range(len(T)):  # interpolate unmatched transcript words between matched neighbours
  if times[i] is None:
   lo=max((j for j in known if j<i),default=None);hi=min((j for j in known if j>i),default=None)
   # speech pace (~0.35 s/word) from the last heard word, so a gap the recogniser skipped never pushes the start late
   times[i]=times[hi] if lo is None else times[lo]+0.35*(i-lo) if hi is None else times[lo]+min(times[hi]-times[lo],0.35*(i-lo))
 first={};
 for i,k in enumerate(owner):first.setdefault(k,i)
 return T,owner,times,marks,first,matched/max(1,len(T))

def find(T,owner,k,phrase):
 p=tok(phrase)
 for size in (len(p),3,2):
  q=p[:size]
  for i in range(len(T)-len(q)+1):
   if owner[i]==k and T[i:i+len(q)]==q:return i
 return None

def main(asr):
 cues8=json.loads((ROOT/'scripts/vol8-evidence-cues.json').read_text())
 cues9=json.loads((ROOT/'scripts/vol9-evidence-cues.json').read_text()).get('listening',{})
 out={};report=[]
 for vol,folder,cues in ((8,'Listening - Vol 8',cues8),(9,'Listening - Vol 9',cues9)):
  for js in sorted((ROOT/'dist'/folder).glob('Test */test.js'),key=lambda p:int(p.parent.name.split()[1])):
   test=load(js);tid=int(js.parent.name.split()[1]);key=f'listening:{vol}:{tid}';times_q={};how={}
   for sec in range(1,5):
    f=pathlib.Path(asr)/f'v{vol}-t{tid}-s{sec}.json'
    if not f.exists():continue
    segs=test['transcriptSegments'][str(sec)];T,owner,times,marks,first,rate=align(segs,json.loads(f.read_text()))
    report.append(f'{key} s{sec}: {rate:.0%} transcript words matched')
    assert rate>0.6,(key,sec,rate)
    ids=[s['id'] for s in segs]
    for n in range(1,41):
     if section_of(test,n)!=sec:continue
     ev=[i for i in test['questionSegments'].get(str(n),[]) if i in ids]
     k=ids.index(ev[0]) if ev else None;at=None
     cue=(test.get('evidenceCues') or {}).get(str(n)) or (cues.get(str(tid),{}).get(str(n)) if vol==9 else None)
     if cue and re.fullmatch(r'Q\d+',cue) and n in marks:at=marks[n];how[n]='label'
     elif k is not None and cue:at=find(T,owner,k,cue);how[n]='cue' if at is not None else None
     if at is None and k is not None and (test.get('questionTypes') or {}).get(str(n),'gap' if not re.fullmatch(r'[A-K](/[A-K])*',test['answers'][str(n)][0]) else 'choice')=='gap':
      for v in test['answers'][str(n)]:
       at=find(T,owner,k,v)
       if at is not None:how[n]='answer';break
     if at is None and k is not None:at=first[k];how[n]='paragraph'
     if at is None:continue
     times_q[str(n)]=[sec,round(max(0.0,times[min(at,len(times)-1)]-LEAD),1)]
   if times_q:out[key]=times_q;report.append(f'{key}: {len(times_q)} questions timed ('+', '.join(f'{m} {list(how.values()).count(m)}' for m in ('label','cue','answer','paragraph'))+')')
 (ROOT/'dist/audio-times.js').write_text('// Generated by scripts/align-audio-times.py: [section, seconds] where each question is answered (minus a short lead-in).\nwindow.AUDIO_TIMES='+json.dumps(out,separators=(',',':'))+';\n')
 (ROOT/'scripts/align-audio-times-report.txt').write_text('\n'.join(report)+'\n');print('\n'.join(r for r in report if 'timed' in r))

if __name__=='__main__':main(sys.argv[1])
